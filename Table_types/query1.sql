-- CREATE DATABASE AND SCHEMA

CREATE OR REPLACE DATABASE HOSPITAL_DB;
CREATE OR REPLACE SCHEMA HOSPITAL_DB.PATIENT_SCHEMA;

-- CREATE FILE FORMAT
CREATE OR REPLACE FILE FORMAT PATIENT_CSV_FORMAT
    TYPE = CSV,
    FIELD_DELIMITER = ',',
    SKIP_HEADER = 1;

-- CREATE INTERNAL STAGE
CREATE OR REPLACE STAGE PATIENT_STAGE
    FILE_FORMAT = PATIENT_CSV_FORMAT;

-- CREATE PERMANENT TABLE
CREATE OR REPLACE TABLE PATIENT_PERM (
    PATIENT_ID INT,
    PATIENT_NAME STRING,
    DEPARTMENT STRING,
    AGE INT,
    CITY STRING
);

-- CREATE TRANSIENT TABLE
CREATE OR REPLACE TRANSIENT TABLE PATIENT_TRANS (
    PATIENT_ID INT,
    PATIENT_NAME STRING,
    DEPARTMENT STRING,
    AGE INT,
    CITY STRING
);

-- CREATE TEMPORARY TABLE
CREATE OR REPLACE TEMPORARY TABLE PATIENT_TEMP (
    PATIENT_ID INT,
    PATIENT_NAME STRING,
    DEPARTMENT STRING,
    AGE INT,
    CITY STRING
);

